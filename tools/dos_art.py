#!/usr/bin/env python3
"""Copy the DOS game's art from PrinceJS (Unlicense) for the renderer.

Reads the PrinceJS archive and writes:

  assets/dos/*.png       the sprite sheets (tiles, characters, swords, flames)
  src/gen/dos_atlas.rs   each sheet's frames (name, x, y, w, h), sorted by
                         name; the DOS sword table; each level's guard
                         colours by room

Usage: tools/dos_art.py [path-to-PrinceJS-zip]
"""

import json
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_REF = os.path.join(HERE, "..", "..", "..", "references", "Prince of Persia", "PrinceJS-master.zip")
PREFIX = "PrinceJS-master/assets/"
SHEETS = ["dungeon", "palace", "general", "kid", "shadow", "skeleton", "fatguard", "jaffar", "sword", "princess", "vizier", "mouse"] + [
    f"guard-{i}" for i in range(1, 8)
]


def ident(name):
    return name.upper().replace("-", "_")


def main():
    z = zipfile.ZipFile(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_REF)
    out_dir = os.path.join(ROOT, "assets", "dos")
    os.makedirs(out_dir, exist_ok=True)
    rs = [
        "// Generated by tools/dos_art.py from PrinceJS's DOS art (Unlicense).",
        "// Do not edit by hand; rerun the tool.",
        "",
        "/// A sheet's frames: name, x, y, w, h, sorted by name.",
        "pub type Frames = &'static [(&'static str, u16, u16, u16, u16)];",
        "",
    ]
    for s in SHEETS:
        with open(os.path.join(out_dir, s + ".png"), "wb") as f:
            f.write(z.read(PREFIX + f"gfx/{s}.png"))
        frames = json.loads(z.read(PREFIX + f"gfx/{s}.json"))["frames"]
        items = frames.items() if isinstance(frames, dict) else [(f["filename"], f) for f in frames]
        rows = sorted((n, f["frame"]) for n, f in items)
        rs.append(f"pub static {ident(s)}: Frames = &[")
        for n, r in rows:
            rs.append(f'    ("{n}", {r["x"]}, {r["y"]}, {r["w"]}, {r["h"]}),')
        rs.append("];")
        rs.append("")

    sword = json.loads(z.read(PREFIX + "anims/sword.json"))["swordtab"]
    rs.append("/// The DOS sword table (Fsword 1-based): image, dx, dy.")
    rs.append(f"pub static SWORDTAB: [(u8, i8, i8); {len(sword)}] = [")
    for e in sword:
        rs.append(f'    ({e["id"]}, {e["dx"]}, {e["dy"]}),')
    rs.append("];")
    rs.append("")

    rs.append("/// Each level's guards: (room, colour 1-7), from the DOS levels.")
    rs.append("pub static GUARD_COLORS: [&[(u8, u8)]; 15] = [")
    for n in range(15):
        try:
            m = json.loads(z.read(PREFIX + f"maps/level{n}.json"))
            g = [(x["room"], x["colors"]) for x in m["guards"] if x.get("type") == "guard"]
        except KeyError:
            g = []
        rs.append("    &[" + ", ".join(f"({r}, {c})" for r, c in g) + "],")
    rs.append("];")

    with open(os.path.join(ROOT, "src", "gen", "dos_atlas.rs"), "w") as f:
        f.write("\n".join(rs) + "\n")
    print(f"{len(SHEETS)} sheets, sword table of {len(sword)}")


if __name__ == "__main__":
    main()
